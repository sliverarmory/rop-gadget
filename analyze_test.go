func TestArchivedReferenceCountSimilarityX86(t *testing.T) {
	t.Parallel()

	opts := DefaultOptions()
	opts.Binary = fixturePath("elf-Linux-x86")
	opts.Depth = 3

	result, err := Analyze(context.Background(), opts)
	if err != nil {
		t.Fatalf("Analyze() error = %v", err)
	}

	reference := referenceUniqueCount(t, "RUN elf-Linux-x86 --depth 3")
	got := len(result.Gadgets)
	lower := int(float64(reference) * 0.60)
	upper := int(float64(reference) * 1.50)
	if got < lower || got > upper {
		t.Fatalf("expected gadget count to stay within [%d, %d] around reference %d, got %d", lower, upper, reference, got)
	}
}

func TestPythonInteropWhenAvailable(t *testing.T) {
	if !pythonInteropAvailable() {
		t.Skip("python3 capstone is not installed in this environment")
	}

	opts := DefaultOptions()
	opts.Binary = fixturePath("elf-Linux-x86")
	opts.Depth = 3

	result, err := Analyze(context.Background(), opts)
	if err != nil {
		t.Fatalf("Analyze() error = %v", err)
	}

	cmd := exec.Command("python3", filepath.Join("ROPgadget", "ROPgadget.py"), "--binary", opts.Binary, "--depth", "3")
	cmd.Env = append(os.Environ(), "PYTHONPATH="+filepath.Join(".", "ROPgadget"))
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("python interoperability run failed: %v\n%s", err, out)
	}

	re := regexp.MustCompile(`Unique gadgets found: (\d+)`)
	matches := re.FindStringSubmatch(string(out))
	if len(matches) != 2 {
		t.Fatalf("could not parse python gadget count from output:\n%s", out)
	}
	pythonCount := atoi(t, matches[1])
	goCount := len(result.Gadgets)
	lower := int(float64(pythonCount) * 0.60)
	upper := int(float64(pythonCount) * 1.50)
	if goCount < lower || goCount > upper {
		t.Fatalf("expected Go gadget count to stay within [%d, %d] around python count %d, got %d", lower, upper, pythonCount, goCount)
	}
}

