func TestFixtureMatrixSmoke(t *testing.T) {
	cases := []struct {
		name       string
		opts       func() Options
		minCount   int
		wantPrefix []string
	}{
		{
			name: "x86-elf",
			opts: func() Options {
				opts := DefaultOptions()
				opts.Binary = fixturePath("elf-Linux-x86")
				opts.Depth = 3
				return opts
			},
			minCount:   8000,
			wantPrefix: []string{"ret", "jmp ", "call "},
		},
		{
			name: "armv7-elf",
			opts: func() Options {
				opts := DefaultOptions()
				opts.Binary = fixturePath("elf-ARMv7-ls")
				opts.Depth = 5
				return opts
			},
			minCount:   300,
			wantPrefix: []string{"bx ", "blx ", "ldm"},
		},
		{
			name: "arm64-elf",
			opts: func() Options {
				opts := DefaultOptions()
				opts.Binary = fixturePath("elf-ARM64-bash")
				opts.Depth = 5
				return opts
			},
			minCount:   200,
			wantPrefix: []string{"br ", "blr ", "ret"},
		},
		{
			name: "riscv64-elf",
			opts: func() Options {
				opts := DefaultOptions()
				opts.Binary = fixturePath("elf-Linux-RISCV_64")
				opts.Depth = 8
				return opts
			},
			minCount:   20,
			wantPrefix: []string{"jr ", "jalr ", "ret", "c.ret"},
		},
	}

	for _, tc := range cases {
		tc := tc
		t.Run(tc.name, func(t *testing.T) {
			result, err := Analyze(context.Background(), tc.opts())
			if err != nil {
				t.Fatalf("Analyze() error = %v", err)
			}
			if got := len(result.Gadgets); got < tc.minCount {
				t.Fatalf("expected at least %d gadgets, got %d", tc.minCount, got)
			}
			if !hasPrefixGadget(result.Gadgets, tc.wantPrefix...) {
				t.Fatalf("expected a gadget starting with one of %v", tc.wantPrefix)
			}
		})
	}
}

