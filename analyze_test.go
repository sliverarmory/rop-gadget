func assembleX86(t *testing.T, mode keystone.Mode, src string) []byte {
	t.Helper()
	engine, err := keystone.NewEngine(keystone.ARCH_X86, mode)
	if err != nil {
		t.Fatalf("keystone.NewEngine() error = %v", err)
	}
	defer func() { _ = engine.Close() }()
	if err := engine.Option(keystone.OPT_SYNTAX, keystone.OPT_SYNTAX_INTEL); err != nil {
		t.Fatalf("engine.Option() error = %v", err)
	}
	out, err := engine.Assemble(src, 0)
	if err != nil {
		t.Fatalf("engine.Assemble() error = %v", err)
	}
	return out
}

func writeTempBinary(t *testing.T, data []byte) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), "code.bin")
	if err := os.WriteFile(path, data, 0o644); err != nil {
		t.Fatalf("os.WriteFile() error = %v", err)
	}
	return path
}

func fixturePath(name string) string {
	return filepath.Join("testdata", "test-suite-binaries", name)
}

func containsLine(lines []string, want string) bool {
	for _, line := range lines {
		if line == want {
			return true
		}
	}
	return false
}

func hasPrefixGadget(gadgets []Gadget, prefixes ...string) bool {
	for _, gadget := range gadgets {
		for _, prefix := range prefixes {
			if strings.HasPrefix(gadget.Text, prefix) {
				return true
			}
		}
	}
	return false
}

func referenceUniqueCount(t *testing.T, run string) int {
	t.Helper()
	file, err := os.Open(filepath.Join("testdata", "test-suite-binaries", "ref_output.bz2"))
	if err != nil {
		t.Fatalf("os.Open() error = %v", err)
	}
	defer file.Close()

	body, err := io.ReadAll(bzip2.NewReader(file))
	if err != nil {
		t.Fatalf("io.ReadAll() error = %v", err)
	}

	lines := strings.Split(string(body), "\n")
	for i, line := range lines {
		if strings.TrimSpace(line) != run {
			continue
		}
		for _, candidate := range lines[i+1:] {
			candidate = strings.TrimSpace(candidate)
			if strings.HasPrefix(candidate, "RUN ") {
				break
			}
			if strings.HasPrefix(candidate, "Unique gadgets found: ") {
				return atoi(t, strings.TrimPrefix(candidate, "Unique gadgets found: "))
			}
		}
	}
	t.Fatalf("reference run %q not found", run)
	return 0
}

func atoi(t *testing.T, value string) int {
	t.Helper()
	out, err := strconv.Atoi(strings.TrimSpace(value))
	if err != nil {
		t.Fatalf("strconv.Atoi(%q) error = %v", value, err)
	}
	return out
}

func pythonInteropAvailable() bool {
	cmd := exec.Command("python3", "-c", "import capstone")
	return cmd.Run() == nil
}
