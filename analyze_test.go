func TestSyntheticRawX86Gadgets(t *testing.T) {
	t.Parallel()

	code := assembleX86(t, keystone.MODE_32, ".code32\nnop\npop eax\nret\nxor eax, eax\nret\nint 0x80\n")
	path := writeTempBinary(t, code)

	opts := DefaultOptions()
	opts.Binary = path
	opts.RawArch = "x86"
	opts.RawMode = "32"
	opts.Depth = 5

	result, err := Analyze(context.Background(), opts)
	if err != nil {
		t.Fatalf("Analyze() error = %v", err)
	}

	texts := make([]string, 0, len(result.Gadgets))
	for _, gadget := range result.Gadgets {
		texts = append(texts, gadget.Text)
	}
	if !containsLine(texts, "ret") {
		t.Fatalf("expected a plain ret gadget, got %v", texts)
	}
	if !containsLine(texts, "pop eax ; ret") {
		t.Fatalf("expected a pop eax ; ret gadget, got %v", texts)
	}
	if !containsLine(texts, "xor eax, eax ; ret") {
		t.Fatalf("expected a xor eax, eax ; ret gadget, got %v", texts)
	}
}

